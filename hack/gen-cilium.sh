#!/bin/sh
# Regenerates internal/render/assets/cilium.yaml, the Cilium manifest that
# `hydra cluster render` embeds in each cluster's ClusterResourceSet ConfigMap.
#
# Run it when CILIUM_VERSION or hack/cilium-values.yaml changes; never edit the
# output by hand. The values live in hack/cilium-values.yaml, the one canonical
# set every installer of Cilium on a Hydra cluster uses (PET-94); its header
# lists the per-cluster sentinels the CLI substitutes. A sentinel that survives
# into the output is caught by the render tests.
#
# operator.replicas is rendered as 1. The CLI raises it to 2 for clusters that
# always have at least two nodes, by rewriting the two lines the chart derives
# from it; this script checks that a render with 2 differs in exactly those
# lines, so a chart upgrade that changes that fails here, not in a cluster.
set -eu

CILIUM_VERSION=${CILIUM_VERSION:-1.19.1}
KUBE_VERSION=${KUBE_VERSION:-1.35.3}
HELM=${HELM:-helm}
here=$(dirname "$0")
out=${OUT:-$here/../internal/render/assets/cilium.yaml}
values=$here/cilium-values.yaml

# Use a throwaway Helm configuration, so this neither reads nor changes the
# caller's repositories, and pin the Kubernetes version the chart renders for.
work=$(mktemp -d)
trap 'rm -r "$work"' EXIT
export HELM_REPOSITORY_CONFIG="$work/repositories.yaml" HELM_REPOSITORY_CACHE="$work/cache" HELM_CACHE_HOME="$work/cache"

render() {
  "$HELM" template cilium cilium --repo https://helm.cilium.io --version "$CILIUM_VERSION" \
    --kube-version "$KUBE_VERSION" \
    --namespace kube-system \
    -f "$values" "$@"
}

{
  printf '# Code generated by hack/gen-cilium.sh from cilium/cilium %s. DO NOT EDIT.\n' "$CILIUM_VERSION"
  render
} > "$out"

# The CLI's two-replica rewrite (render.operatorHA) must match the chart.
render --set operator.replicas=2 > "$work/two.yaml"
sed 1d "$out" | diff - "$work/two.yaml" > "$work/diff" || true
expected='<   replicas: 1
---
>   replicas: 2
<       maxUnavailable: 100%
---
>       maxUnavailable: 50%'
if [ "$(grep -v '^[0-9]' "$work/diff")" != "$expected" ]; then
  echo "operator.replicas=2 changes more than the two lines the CLI rewrites; update render.operatorHA:" >&2
  cat "$work/diff" >&2
  exit 1
fi

echo "wrote $out ($(wc -c < "$out") bytes)"
